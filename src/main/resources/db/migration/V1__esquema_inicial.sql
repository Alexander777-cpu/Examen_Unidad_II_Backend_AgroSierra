CREATE TABLE lotes (
    id                         NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY,
    codigo                     VARCHAR2(30 CHAR)  NOT NULL,
    nombre                     VARCHAR2(100 CHAR) NOT NULL,
    hectareas                  NUMBER(8, 2)       NOT NULL,
    cultivo                    VARCHAR2(80 CHAR)  NOT NULL,
    valle                      VARCHAR2(80 CHAR)  NOT NULL,
    campania_cerrada           NUMBER(1, 0)       DEFAULT 0 NOT NULL,
    dosis_maxima_por_hectarea  NUMBER(8, 2)       NOT NULL,
    CONSTRAINT pk_lotes PRIMARY KEY (id),
    CONSTRAINT ux_lotes_codigo UNIQUE (codigo),
    CONSTRAINT ck_lotes_campania CHECK (campania_cerrada IN (0, 1)),
    CONSTRAINT ck_lotes_hectareas CHECK (hectareas > 0)
);

CREATE UNIQUE INDEX ux_lotes_nombre ON lotes (UPPER(nombre));
CREATE INDEX ix_lotes_valle ON lotes (valle);

CREATE TABLE labores (
    id                 NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY,
    lote_id            NUMBER(19, 0)      NOT NULL,
    tipo               VARCHAR2(20 CHAR)  NOT NULL,
    fecha              VARCHAR2(10 CHAR)  NOT NULL,
    responsable        VARCHAR2(50 CHAR)  NOT NULL,
    cantidad           NUMBER(10, 2)      NOT NULL,
    observacion        VARCHAR2(255 CHAR),
    fecha_registro     TIMESTAMP(6)       DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_labores PRIMARY KEY (id),
    CONSTRAINT fk_labores_lote FOREIGN KEY (lote_id)
        REFERENCES lotes (id) ON DELETE CASCADE,
    CONSTRAINT ck_labores_tipo CHECK (tipo IN ('RIEGO', 'FUMIGACION', 'COSECHA')),
    CONSTRAINT ck_labores_cantidad CHECK (cantidad > 0)
);

CREATE INDEX ix_labores_lote ON labores (lote_id);
CREATE INDEX ix_labores_fecha ON labores (fecha);