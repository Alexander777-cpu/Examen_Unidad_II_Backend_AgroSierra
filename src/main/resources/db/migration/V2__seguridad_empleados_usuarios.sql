CREATE TABLE roles (
    id                 NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY,
    nombre             VARCHAR2(50 CHAR)  NOT NULL,
    descripcion        VARCHAR2(150 CHAR),
    CONSTRAINT pk_roles PRIMARY KEY (id),
    CONSTRAINT ux_roles_nombre UNIQUE (nombre)
);

CREATE TABLE privilegios (
    id                 NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY,
    nombre             VARCHAR2(50 CHAR)  NOT NULL,
    descripcion        VARCHAR2(150 CHAR),
    CONSTRAINT pk_privilegios PRIMARY KEY (id),
    CONSTRAINT ux_privilegios_nombre UNIQUE (nombre)
);

CREATE TABLE rol_privilegios (
    rol_id             NUMBER(19, 0) NOT NULL,
    privilegio_id      NUMBER(19, 0) NOT NULL,
    CONSTRAINT pk_rol_privilegios PRIMARY KEY (rol_id, privilegio_id),
    CONSTRAINT fk_rp_rol FOREIGN KEY (rol_id)
        REFERENCES roles (id) ON DELETE CASCADE,
    CONSTRAINT fk_rp_privilegio FOREIGN KEY (privilegio_id)
        REFERENCES privilegios (id) ON DELETE CASCADE
);

CREATE TABLE usuarios (
    id                 NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY,
    username           VARCHAR2(50 CHAR)  NOT NULL,
    password           VARCHAR2(100 CHAR) NOT NULL,
    nombre_completo    VARCHAR2(120 CHAR),
    estado             NUMBER(1, 0)       DEFAULT 1 NOT NULL,
    fecha_creacion     TIMESTAMP(6)       DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_usuarios PRIMARY KEY (id),
    CONSTRAINT ux_usuarios_username UNIQUE (username),
    CONSTRAINT ck_usuarios_estado CHECK (estado IN (0, 1))
);

CREATE TABLE usuario_roles (
    usuario_id         NUMBER(19, 0) NOT NULL,
    rol_id             NUMBER(19, 0) NOT NULL,
    CONSTRAINT pk_usuario_roles PRIMARY KEY (usuario_id, rol_id),
    CONSTRAINT fk_ur_usuario FOREIGN KEY (usuario_id)
        REFERENCES usuarios (id) ON DELETE CASCADE,
    CONSTRAINT fk_ur_rol FOREIGN KEY (rol_id)
        REFERENCES roles (id) ON DELETE CASCADE
);